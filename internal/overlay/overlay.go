// Package overlay writes the small per-shell kubeconfig that kdir puts at the
// front of KUBECONFIG.
//
// An overlay contains only current-context and context entries. Context
// entries hold references (cluster name, user name, namespace) and never
// credentials or cluster definitions; those keep coming from the user's real
// kubeconfig files further down the KUBECONFIG list.
//
// Every context from the real kubeconfig is copied, not only the target. kubectl
// writes a modified context back to the file the context was loaded from, so
// copying them all means `kubectl config use-context other && kubens foo` in a
// governed shell changes the overlay, never the user's real files.
package overlay

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"syscall"

	"k8s.io/client-go/tools/clientcmd"
	clientcmdapi "k8s.io/client-go/tools/clientcmd/api"
	"sigs.k8s.io/yaml"
)

// File is the on-disk shape of an overlay. It deliberately has no clusters or
// users fields.
type File struct {
	APIVersion     string         `json:"apiVersion"`
	Kind           string         `json:"kind"`
	CurrentContext string         `json:"current-context"`
	Contexts       []NamedContext `json:"contexts"`
}

// NamedContext is a context entry in an overlay.
type NamedContext struct {
	Name    string     `json:"name"`
	Context ContextRef `json:"context"`
}

// ContextRef holds only references to entries in the real kubeconfig.
type ContextRef struct {
	Cluster   string `json:"cluster"`
	User      string `json:"user"`
	Namespace string `json:"namespace,omitempty"`
}

// Build returns an overlay that selects current with the given namespace.
// cfg is the user's merged real kubeconfig and may be nil (for example when it
// failed to load). If current is not a context in cfg, the overlay selects a
// context that does not exist, which makes kubectl fail closed.
func Build(cfg *clientcmdapi.Config, current, namespace string) *File {
	f := &File{APIVersion: "v1", Kind: "Config", CurrentContext: current, Contexts: []NamedContext{}}
	if cfg == nil {
		return f
	}
	names := make([]string, 0, len(cfg.Contexts))
	for name, c := range cfg.Contexts {
		if c != nil {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	for _, name := range names {
		c := cfg.Contexts[name]
		ref := ContextRef{Cluster: c.Cluster, User: c.AuthInfo, Namespace: c.Namespace}
		if name == current {
			ref.Namespace = namespace
		}
		f.Contexts = append(f.Contexts, NamedContext{Name: name, Context: ref})
	}
	return f
}

// Marshal renders the overlay as YAML.
func (f *File) Marshal() ([]byte, error) {
	b, err := yaml.Marshal(f)
	if err != nil {
		return nil, err
	}
	return append([]byte("# Generated by kdir for one shell. Safe to delete; contains no credentials.\n"), b...), nil
}

var unsafeChars = regexp.MustCompile(`[^A-Za-z0-9._-]+`)

// FailClosedName returns a context name that is guaranteed not to exist in
// cfg, used as current-context so kubectl errors instead of falling back to
// whatever context was active. reason is e.g. "missing", want is the name or
// matcher the spec asked for (may be empty).
func FailClosedName(cfg *clientcmdapi.Config, reason, want string) string {
	name := "kdir-" + reason
	if w := strings.Trim(unsafeChars.ReplaceAllString(want, "-"), "-"); w != "" {
		if len(w) > 60 {
			w = w[:60]
		}
		name += "-" + w
	}
	if cfg == nil {
		return name
	}
	candidate := name
	for i := 2; ; i++ {
		if _, exists := cfg.Contexts[candidate]; !exists {
			return candidate
		}
		candidate = name + "-" + strconv.Itoa(i)
	}
}

// Dir returns the directory overlays live in, creating it with mode 0700:
// $XDG_RUNTIME_DIR/kdir, or <os.TempDir()>/kdir-<uid>. It refuses to use a
// directory that is a symlink, is not owned by the current user, or is
// accessible by others, since another user could otherwise swap overlays.
func Dir(getenv func(string) string) (string, error) {
	var dir string
	if x := getenv("XDG_RUNTIME_DIR"); x != "" && filepath.IsAbs(x) {
		dir = filepath.Join(x, "kdir")
	} else {
		tmp := getenv("TMPDIR")
		if tmp == "" || !filepath.IsAbs(tmp) {
			tmp = os.TempDir()
		}
		dir = filepath.Join(tmp, "kdir-"+strconv.Itoa(os.Getuid()))
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	if err := checkPrivateDir(dir); err != nil {
		return "", err
	}
	return dir, nil
}

func checkPrivateDir(dir string) error {
	fi, err := os.Lstat(dir)
	if err != nil {
		return err
	}
	if fi.Mode()&fs.ModeSymlink != 0 || !fi.IsDir() {
		return fmt.Errorf("%s is not a directory", dir)
	}
	if st, ok := fi.Sys().(*syscall.Stat_t); ok && int(st.Uid) != os.Getuid() {
		return fmt.Errorf("%s is owned by another user", dir)
	}
	if fi.Mode().Perm()&0o077 != 0 {
		if err := os.Chmod(dir, 0o700); err != nil {
			return fmt.Errorf("%s is accessible by other users: %w", dir, err)
		}
	}
	return nil
}

// Path returns the overlay path for a shell PID.
func Path(dir string, pid int) string {
	return filepath.Join(dir, strconv.Itoa(pid)+".yaml")
}

// PIDFromPath returns the shell PID encoded in an overlay file name.
func PIDFromPath(path string) (int, bool) {
	base := filepath.Base(path)
	if !strings.HasSuffix(base, ".yaml") {
		return 0, false
	}
	pid, err := strconv.Atoi(strings.TrimSuffix(base, ".yaml"))
	return pid, err == nil && pid > 0
}

// Write atomically writes f to path with mode 0600.
func Write(path string, f *File) error {
	data, err := f.Marshal()
	if err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".tmp-*")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(tmp.Name()) }()
	if err := tmp.Chmod(0o600); err != nil {
		_ = tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// HasCredentials reports whether something (typically `aws eks
// update-kubeconfig` or `kubectl config set-credentials`, which write to the
// first KUBECONFIG entry) has added clusters or users to an overlay. Such an
// overlay must not be deleted silently.
func HasCredentials(path string) (bool, error) {
	cfg, err := clientcmd.LoadFromFile(path)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return false, nil
		}
		return false, err
	}
	return len(cfg.Clusters) > 0 || len(cfg.AuthInfos) > 0, nil
}

// ErrHasCredentials is returned by Remove when the overlay was kept because it
// contains clusters or users.
var ErrHasCredentials = errors.New("overlay contains clusters or users written by another tool; kept")

// Remove deletes an overlay. It does not delete an overlay that has gained
// clusters or users; it returns ErrHasCredentials instead so the caller can
// tell the user where the file is. A missing file is not an error.
func Remove(path string) error {
	has, err := HasCredentials(path)
	if err != nil {
		return err
	}
	if has {
		return ErrHasCredentials
	}
	if err := os.Remove(path); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	return nil
}
